import h203 from './worker-h203.js';

const BUILD='H204';
function headers(contentType){return{'content-type':contentType,'cache-control':'no-store, max-age=0, must-revalidate','pragma':'no-cache','expires':'0','x-mtg-build':BUILD}}
function stamp(source){return source.replace(/MTG TableTop\s+H\d+/g,'MTG TableTop '+BUILD).replace(/Game loaded\s*[·.]\s*H\d+/g,'Game loaded · '+BUILD)}

function transformHtml(source){
  let out=stamp(source);
  if(out.includes('h204-opponent-pile-shadow-cleanup'))return out;

  const css=`<style id="h204-opponent-pile-shadow-cleanup">
/* H204 keeps the confirmed H203 pile geometry intact. The dedicated Opponent
   overlay was still inheriting the global inset pile shadow, which creates the
   darker inner-edge effect. Remove only that shadow on the Opponent screen. */
body.h157-opp-mode #h157-opp-piles .zone,
body.h157-opp-mode #h157-opp-piles .cmd{
  box-shadow:none!important;
}
</style>`;
  out=out.replace('</head>',css+'</head>');
  return out;
}

export default{
  async fetch(request,env,ctx){
    const url=new URL(request.url);
    if(url.pathname==='/api/health')return new Response(JSON.stringify({ok:true,build:BUILD}),{status:200,headers:headers('application/json; charset=utf-8')});
    const response=await h203.fetch(request,env,ctx);
    if(url.pathname==='/'||url.pathname==='/index.html'||url.pathname==='/game'||url.pathname==='/game.html'||url.pathname==='/api/html-test'){
      const text=await response.text();
      return new Response(transformHtml(text),{status:response.status,headers:headers(response.headers.get('content-type')||'text/html; charset=utf-8')});
    }
    return response;
  }
};
